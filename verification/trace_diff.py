"""Trace Diff Verification Utility for BTP Part II (Task UA.8).

Compares hierarchical simulation traces against golden reference traces generated by
the integer oracle (numerics/decoder.py).
Directory layout:
<trace_dir>/seq<id>/tok<idx>/L<layer>/<op>_<tensor>.hex

Reports the FIRST diverging:
(seq_id, token_idx, layer, op, tensor, element_idx, expected_val, actual_val)
"""

import argparse
import sys
from dataclasses import dataclass
from pathlib import Path


@dataclass
class DivergencePoint:
    """Exact location and values of the first divergence between traces."""
    seq_id: str
    token_idx: str
    layer: str
    op_name: str
    tensor_name: str
    element_idx: int
    expected_hex: str
    actual_hex: str

    def __str__(self) -> str:
        return (
            f"DIVERGENCE at seq={self.seq_id}, tok={self.token_idx}, layer={self.layer}, "
            f"op={self.op_name}, tensor={self.tensor_name}, elem[{self.element_idx}]: "
            f"expected={self.expected_hex}, actual={self.actual_hex}"
        )


@dataclass
class DiffResult:
    """Outcome of comparing two trace directory trees."""
    is_identical: bool
    total_files_checked: int
    total_elements_checked: int
    first_divergence: DivergencePoint | None = None
    missing_files: list[str] = None

    def __post_init__(self):
        if self.missing_files is None:
            self.missing_files = []


def diff_trace_files(golden_file: Path, actual_file: Path) -> tuple[bool, int, int | None, str | None, str | None]:
    """Compare two hex trace files line by line."""
    g_lines = [line.strip() for line in golden_file.read_text().splitlines() if line.strip()]
    a_lines = [line.strip() for line in actual_file.read_text().splitlines() if line.strip()]

    total = len(g_lines)
    if len(g_lines) != len(a_lines):
        min_len = min(len(g_lines), len(a_lines))
        for idx in range(min_len):
            if g_lines[idx].lower() != a_lines[idx].lower():
                return False, idx, idx, g_lines[idx], a_lines[idx]
        return False, min_len, min_len, f"len={len(g_lines)}", f"len={len(a_lines)}"

    for idx, (g, a) in enumerate(zip(g_lines, a_lines, strict=True)):
        if g.lower() != a.lower():
            return False, total, idx, g, a

    return True, total, None, None, None


def compare_trace_directories(golden_dir: Path, actual_dir: Path) -> DiffResult:
    """Recursively compare all trace files between golden and actual directories."""
    golden_files = sorted(golden_dir.rglob("*.hex"))
    if not golden_files:
        golden_files = sorted(golden_dir.rglob("*.txt"))

    total_files = 0
    total_elements = 0
    missing = []

    for g_path in golden_files:
        rel_path = g_path.relative_to(golden_dir)
        a_path = actual_dir / rel_path

        if not a_path.exists():
            missing.append(str(rel_path))
            continue

        total_files += 1
        is_match, count, elem_idx, exp_val, act_val = diff_trace_files(g_path, a_path)
        total_elements += count

        if not is_match:
            # Parse path parts: seq0/tok0/L0/op_tensor.hex
            parts = rel_path.parts
            seq_id = parts[0] if len(parts) > 0 else "?"
            tok_idx = parts[1] if len(parts) > 1 else "?"
            layer = parts[2] if len(parts) > 2 else "?"
            stem = g_path.stem
            op_name = stem.split("_")[0] if "_" in stem else stem
            tensor_name = "_".join(stem.split("_")[1:]) if "_" in stem else stem

            divergence = DivergencePoint(
                seq_id=seq_id,
                token_idx=tok_idx,
                layer=layer,
                op_name=op_name,
                tensor_name=tensor_name,
                element_idx=elem_idx if elem_idx is not None else -1,
                expected_hex=exp_val or "?",
                actual_hex=act_val or "?",
            )
            return DiffResult(
                is_identical=False,
                total_files_checked=total_files,
                total_elements_checked=total_elements,
                first_divergence=divergence,
                missing_files=missing,
            )

    if missing:
        return DiffResult(
            is_identical=False,
            total_files_checked=total_files,
            total_elements_checked=total_elements,
            first_divergence=None,
            missing_files=missing,
        )

    return DiffResult(
        is_identical=True,
        total_files_checked=total_files,
        total_elements_checked=total_elements,
        first_divergence=None,
        missing_files=[],
    )


def main() -> int:
    parser = argparse.ArgumentParser(description="Hierarchical RTL trace comparator.")
    parser.add_argument("--golden", type=Path, required=True, help="Path to golden trace directory")
    parser.add_argument("--actual", type=Path, required=True, help="Path to actual simulation trace directory")
    parser.add_argument("--quiet", action="store_true", help="Suppress matching output")
    args = parser.parse_args()

    if not args.golden.exists():
        print(f"[-] Golden directory not found: {args.golden}", file=sys.stderr)
        return 2
    if not args.actual.exists():
        print(f"[-] Actual trace directory not found: {args.actual}", file=sys.stderr)
        return 2

    res = compare_trace_directories(args.golden, args.actual)
    if res.is_identical:
        if not args.quiet:
            print(f"[+] TRACE MATCH: {res.total_files_checked} files, {res.total_elements_checked} elements identical.")
        return 0
    else:
        if res.first_divergence:
            print(f"[-] TRACE MISMATCH: {res.first_divergence}", file=sys.stderr)
        if res.missing_files:
            print(f"[-] Missing {len(res.missing_files)} trace files in actual directory.", file=sys.stderr)
        return 1


if __name__ == "__main__":
    sys.exit(main())
