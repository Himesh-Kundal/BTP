"""Full module generator for Design F fixed-weight linear hardware (T4.5).

Generates synthesizable top-level Design F modules:
1. Instantiates all (Nt x Kt) parametric tile cores.
2. Constructs reduction adder trees per output row over column tiles j.
3. Incorporates constant bias terms (if present).
4. Wraps core in registered wrapper with synchronous active-low reset,
   valid handshaking, and fixed latency L=1.
"""

from __future__ import annotations

from backend.codegen import format_signed_literal, sanitize_identifier
from backend.tiling import TileManifest
from backend.verilog_codegen import generate_tile_core
from ir.linear import LinearOp
from ir.tensor import TensorRef


def generate_full_module(
    op: LinearOp,
    manifest: TileManifest,
    tile_n: int = 8,
    tile_k: int = 16,
    latency: int = 1,
    acc_bits: int = 32,
    module_name: str | None = None,
) -> str:
    """Generate complete, synthesizable Design F RTL with all tiles, adder trees, and wrapper.

    Args:
        op: Quantized LinearOp with weights and optional bias.
        manifest: TileManifest containing tiling geometry and individual TileSpecs.
        tile_n: Height of tile (default 8).
        tile_k: Width of tile (default 16).
        latency: Pipeline latency in cycles (default 1).
        acc_bits: Accumulator bit width (default 32).
        module_name: Optional top module name override.

    Returns:
        Complete Verilog-2001 source code containing all tile cores,
        combinational top core, and registered wrapper.
    """
    if module_name is None:
        raw_name = f"llmhw_{op.name}"
    else:
        raw_name = module_name
    clean_mod_name = sanitize_identifier(raw_name)
    core_mod_name = f"{clean_mod_name}_core"

    n_padded = manifest.n_padded
    k_padded = manifest.k_padded
    num_tiles_n = manifest.num_tiles_n
    num_tiles_k = manifest.num_tiles_k

    in_bits = 8 * k_padded
    out_bits = acc_bits * n_padded

    # Extract bias array if present
    bias_arr = None
    if op.bias is not None:
        if isinstance(op.bias, TensorRef):
            bias_arr = op.bias.data
        else:
            bias_arr = op.bias

    sections: list[str] = []

    # File Header
    header = [
        "// =============================================================================",
        f"// Design F Full Module: {clean_mod_name}",
        f"// Shapes: in_features={op.in_features} (padded {k_padded}), out_features={op.out_features} (padded {n_padded})",
        f"// Tiling: Nt={tile_n}, Kt={tile_k}, NumTiles={manifest.total_tiles} ({num_tiles_n}x{num_tiles_k})",
        f"// Latency: {latency} cycle(s), Accumulator: {acc_bits} bits",
        f"// Manifest SHA256: {manifest.manifest_hash}",
        "// Generated by LLMHW compiler — strictly deterministic, no timestamps",
        "// =============================================================================",
        "`timescale 1ns / 1ps",
        "`default_nettype none",
        "/* verilator lint_save */",
        "/* verilator lint_off WIDTHEXPAND */",
        "/* verilator lint_off UNUSEDSIGNAL */",
        "/* verilator lint_off DECLFILENAME */",
        "",
    ]
    sections.append("\n".join(header))

    # 1. Individual Tile Cores
    sections.append("// =============================================================================")
    sections.append("// Tile Core Modules")
    sections.append("// =============================================================================")
    for tile in manifest.tiles:
        tile_rtl = generate_tile_core(
            module_name=tile.module_name,
            weights=tile.weights,
            acc_bits=acc_bits,
            manifest_hash=tile.weight_sha256,
        )
        sections.append(tile_rtl)

    # 2. Top-Level Combinational Core
    core_lines = [
        "// =============================================================================",
        f"// Top Combinational Core: {core_mod_name}",
        "// =============================================================================",
        f"module {core_mod_name} (",
        f"    input  wire [{in_bits - 1}:0] x_flat,",
        f"    output wire [{out_bits - 1}:0] y_flat",
        ");",
        "",
        "    // --- Input Slicing for Column Tiles ---",
    ]

    for j in range(num_tiles_k):
        low_idx = 8 * j * tile_k
        high_idx = 8 * (j + 1) * tile_k - 1
        core_lines.append(f"    wire [{8 * tile_k - 1}:0] x_tile_{j} = x_flat[{high_idx}:{low_idx}];")

    core_lines.append("")
    core_lines.append("    // --- Tile Core Instantiations ---")

    for i in range(num_tiles_n):
        for j in range(num_tiles_k):
            # Tile module name matches what was defined
            clean_layer_name = manifest.layer_name
            tile_mod = f"llmhw_{clean_layer_name}_tile_i{i}_j{j}"
            tile_out = f"y_tile_{i}_{j}"
            core_lines.append(f"    wire [{acc_bits * tile_n - 1}:0] {tile_out};")
            core_lines.append(f"    {tile_mod} u_tile_{i}_{j} (")
            core_lines.append(f"        .x_flat(x_tile_{j}),")
            core_lines.append(f"        .y_flat({tile_out})")
            core_lines.append("    );")

    core_lines.append("")
    core_lines.append("    // --- Adder Trees (Reduction over j) & Bias Addition ---")

    for n in range(n_padded):
        i = n // tile_n
        r = n % tile_n
        term_signals: list[str] = []

        for j in range(num_tiles_k):
            term_name = f"term_{n}_{j}"
            low_b = acc_bits * r
            high_b = acc_bits * (r + 1) - 1
            core_lines.append(f"    wire signed [{acc_bits - 1}:0] {term_name} = y_tile_{i}_{j}[{high_b}:{low_b}];")
            term_signals.append(term_name)

        # Build row sum expression
        if len(term_signals) == 1:
            sum_expr = term_signals[0]
        else:
            sum_expr = " + ".join(term_signals)

        # Incorporate bias if present
        if bias_arr is not None and n < len(bias_arr):
            b_val = int(bias_arr[n])
            if b_val != 0:
                if b_val > 0:
                    sum_expr += f" + {format_signed_literal(b_val, bits=acc_bits)}"
                else:
                    sum_expr += f" - {format_signed_literal(abs(b_val), bits=acc_bits)}"

        core_lines.append(f"    wire signed [{acc_bits - 1}:0] y_row_{n} = {sum_expr};")
        core_lines.append(f"    assign y_flat[{acc_bits * n + acc_bits - 1}:{acc_bits * n}] = y_row_{n};")
        core_lines.append("")

    core_lines.append("endmodule")
    sections.append("\n".join(core_lines))

    # 3. Top-Level Registered Wrapper
    wrapper_lines = [
        "// =============================================================================",
        f"// Top Registered Wrapper: {clean_mod_name}",
        f"// Fixed Latency L={latency}",
        "// =============================================================================",
        f"module {clean_mod_name} (",
        "    input  wire                           clk,",
        "    input  wire                           rst_n,",
        "    input  wire                           valid_in,",
        f"    input  wire [{in_bits - 1}:0]         x_flat,",
        "    output reg                            valid_out,",
        f"    output reg  [{out_bits - 1}:0]        y_flat",
        ");",
        "",
        f"    wire [{out_bits - 1}:0] y_comb;",
        "",
        f"    {core_mod_name} u_core (",
        "        .x_flat(x_flat),",
        "        .y_flat(y_comb)",
        "    );",
        "",
        "    always @(posedge clk) begin",
        "        if (!rst_n) begin",
        "            valid_out <= 1'b0;",
        "        end else begin",
        "            valid_out <= valid_in;",
        "        end",
        "    end",
        "",
        "    always @(posedge clk) begin",
        "        if (valid_in) begin",
        "            y_flat <= y_comb;",
        "        end",
        "    end",
        "",
        "endmodule",
        "/* verilator lint_restore */",
        "`default_nettype wire",
        "",
    ]
    sections.append("\n".join(wrapper_lines))

    return "\n\n".join(sections)
