"""Verilog-2001 code generator for combinational fixed-weight cores (backend F)."""

import hashlib
import re

from ir.linear import LinearOp


def sanitize_identifier(name: str) -> str:
    """Sanitize string to valid Verilog identifier [a-zA-Z0-9_]."""
    cleaned = re.sub(r"[^a-zA-Z0-9_]", "_", name).lower()
    if cleaned and cleaned[0].isdigit():
        cleaned = "_" + cleaned
    return cleaned


def format_signed_literal(val: int, bits: int = 8) -> str:
    """Format an integer as a Verilog signed decimal literal (e.g. 8'sd3 or -8'sd2)."""
    if val >= 0:
        return f"{bits}'sd{val}"
    else:
        return f"-{bits}'sd{abs(val)}"


def generate_fixed_core(op: LinearOp, module_name: str | None = None) -> str:
    """Generate a synthesizable, combinational fixed-weight Verilog-2001 core module.

    Interface:
        module <name>_core (
            input  wire [8*K-1:0]  x_flat,
            output wire [32*N-1:0] y_flat
        );

    Invariants:
        - No weight input ports or weight registers (Rule 6).
        - Verilog-2001 subset only (Convention 1).
        - All arithmetic operands signed; explicit widths and extensions (Convention 2).
        - Zero-weight terms pruned (Convention 6).
        - Header with content hash, no timestamps or paths (Convention 6).
    """
    if module_name is None:
        raw_name = f"llmhw_{op.name}_core"
        mod_name = sanitize_identifier(raw_name)
    else:
        mod_name = sanitize_identifier(module_name)

    k = op.in_features
    n = op.out_features
    in_bits = 8 * k
    out_bits = 32 * n

    # Compute deterministic content hash for header
    hasher = hashlib.sha256()
    hasher.update(op.weight.tobytes())
    if op.bias is not None:
        hasher.update(op.bias.tobytes())
    content_hash = hasher.hexdigest()[:16]

    lines = [
        "// =============================================================================",
        f"// Fixed-weight core: {mod_name}",
        f"// Shapes: in_features(K)={k}, out_features(N)={n}",
        f"// Content SHA256: {content_hash}",
        "// Generated by LLMHW compiler — strictly deterministic, no timestamps",
        "// =============================================================================",
        "`default_nettype none",
        "",
        f"module {mod_name} (",
        f"    input  wire [{in_bits - 1}:0] x_flat,",
        f"    output wire [{out_bits - 1}:0] y_flat",
        ");",
        "",
        "    // --- Input Unpacking (explicit signed wires) ---",
    ]

    for j in range(k):
        lines.append(f"    wire signed [7:0] x_{j} = x_flat[{8 * j + 7}:{8 * j}];")

    lines.append("")
    lines.append("    // --- Multipliers & Accumulation Trees ---")

    for i in range(n):
        lines.append(f"    // Row {i}:")
        terms_to_sum = []
        for j in range(k):
            w_val = int(op.weight[i, j])
            if w_val == 0:
                # Prune zero weight terms completely
                continue

            prod_sig = f"prod_{i}_{j}"
            ext_sig = f"ext_prod_{i}_{j}"

            if w_val == 1:
                lines.append(f"    wire signed [15:0] {prod_sig} = {{{{8{{x_{j}[7]}}}}, x_{j}}};")
            elif w_val == -1:
                lines.append(f"    wire signed [15:0] {prod_sig} = -{{{{8{{x_{j}[7]}}}}, x_{j}}};")
            else:
                w_lit = format_signed_literal(w_val, bits=8)
                lines.append(f"    wire signed [15:0] {prod_sig} = x_{j} * {w_lit};")

            lines.append(f"    wire signed [31:0] {ext_sig} = {{{{16{{{prod_sig}[15]}}}}, {prod_sig}}};")
            terms_to_sum.append(ext_sig)

        # Handle bias if present
        bias_val = int(op.bias[i]) if op.bias is not None else 0
        bias_term = None
        if bias_val != 0:
            bias_term = format_signed_literal(bias_val, bits=32)

        # Build accumulator expression
        if not terms_to_sum and bias_term is None:
            sum_expr = "32'sd0"
        elif not terms_to_sum and bias_term is not None:
            sum_expr = bias_term
        else:
            sum_expr = " + ".join(terms_to_sum)
            if bias_term is not None:
                if bias_val > 0:
                    sum_expr += f" + {bias_term}"
                else:
                    sum_expr += f" - {format_signed_literal(abs(bias_val), bits=32)}"

        lines.append(f"    wire signed [31:0] y_{i} = {sum_expr};")
        lines.append(f"    assign y_flat[{32 * i + 31}:{32 * i}] = y_{i};")
        lines.append("")

    lines.append("endmodule")
    lines.append("`default_nettype wire")
    lines.append("")
    return "\n".join(lines)
