"""Verilog testbench generator for combinational and registered fixed-weight linear modules."""

from backend.codegen import sanitize_identifier
from ir.linear import LinearOp


def generate_core_testbench(
    op: LinearOp,
    num_vectors: int,
    x_hex_path: str = "x.hex",
    y_hex_path: str = "y_exp.hex",
    module_name: str | None = None,
) -> str:
    """Generate a self-checking plain Verilog-2001 testbench for a combinational core module.

    Per spec docs/02 §7 and docs/06 §A8:
    - Reads x.hex and y_exp.hex via $readmemh.
    - Packs inputs into x_flat, drives DUT, compares y_flat against y_exp.
    - Prints exactly one summary line:
      TB_RESULT CHECKED=<n> MISMATCH=<m> TIMING_ERR=<t>
    - Supports optional +dump plusarg for VCD dump.
    """
    if module_name is None:
        raw_name = f"llmhw_{op.name}_core"
        dut_module = sanitize_identifier(raw_name)
    else:
        dut_module = sanitize_identifier(module_name)

    tb_module = f"{dut_module}_tb"
    k = op.in_features
    n = op.out_features
    in_bits = 8 * k
    out_bits = 32 * n

    total_x_elements = num_vectors * k
    total_y_elements = num_vectors * n

    lines = [
        "// =============================================================================",
        f"// Testbench for: {dut_module}",
        f"// Vectors: {num_vectors}, in_features(K)={k}, out_features(N)={n}",
        "// Generated by LLMHW compiler — strictly deterministic, no timestamps",
        "// =============================================================================",
        "`timescale 1ns / 1ps",
        "`default_nettype none",
        "",
        f"module {tb_module};",
        "",
        f"    parameter NUM_VECTORS = {num_vectors};",
        f"    parameter K = {k};",
        f"    parameter N = {n};",
        "",
        f"    reg  [{in_bits - 1}:0] x_flat;",
        f"    wire [{out_bits - 1}:0] y_flat;",
        "",
        "    // Element memories loaded from hex files",
        f"    reg [7:0]  x_mem [0:{total_x_elements - 1}];",
        f"    reg [31:0] y_mem [0:{total_y_elements - 1}];",
        "",
        "    // Tracking counters",
        "    integer vec_idx, k_idx, n_idx;",
        "    integer checked_count = 0;",
        "    integer mismatch_count = 0;",
        "    integer timing_err_count = 0;",
        "",
        "    reg signed [31:0] y_act_elem;",
        "    reg signed [31:0] y_exp_elem;",
        "",
        "    // Instantiate Device Under Test",
        f"    {dut_module} dut (",
        "        .x_flat(x_flat),",
        "        .y_flat(y_flat)",
        "    );",
        "",
        "    initial begin",
        "        // Optional waveform dump",
        '        if ($test$plusargs("dump")) begin',
        f'            $dumpfile("{dut_module}.vcd");',
        f"            $dumpvars(0, {tb_module});",
        "        end",
        "",
        "        // Load hex vectors",
        f'        $readmemh("{x_hex_path}", x_mem);',
        f'        $readmemh("{y_hex_path}", y_mem);',
        "",
        "        #10;",
        "        for (vec_idx = 0; vec_idx < NUM_VECTORS; vec_idx = vec_idx + 1) begin",
        "            // Pack K elements into x_flat (element 0 in LSBs)",
        "            for (k_idx = 0; k_idx < K; k_idx = k_idx + 1) begin",
        "                x_flat[8*k_idx +: 8] = x_mem[vec_idx*K + k_idx];",
        "            end",
        "",
        "            // Combinational delay for propagation",
        "            #1;",
        "",
        "            // Check N output elements",
        "            for (n_idx = 0; n_idx < N; n_idx = n_idx + 1) begin",
        "                y_act_elem = y_flat[32*n_idx +: 32];",
        "                y_exp_elem = y_mem[vec_idx*N + n_idx];",
        "                if (y_act_elem !== y_exp_elem) begin",
        '                    $display("MISMATCH [vec=%0d, lane=%0d]: expected 0x%08h (%0d), got 0x%08h (%0d)",',
        "                             vec_idx, n_idx, y_exp_elem, y_exp_elem, y_act_elem, y_act_elem);",
        "                    mismatch_count = mismatch_count + 1;",
        "                end",
        "            end",
        "            checked_count = checked_count + 1;",
        "            #9;",
        "        end",
        "",
        "        #10;",
        '        $display("TB_RESULT CHECKED=%0d MISMATCH=%0d TIMING_ERR=%0d", checked_count, mismatch_count, timing_err_count);',
        "        $finish;",
        "    end",
        "",
        "endmodule",
        "`default_nettype wire",
        "",
    ]
    return "\n".join(lines)


def generate_wrapper_testbench(
    op: LinearOp,
    num_vectors: int,
    x_hex_path: str = "x.hex",
    y_hex_path: str = "y_exp.hex",
    module_name: str | None = None,
    latency: int = 1,
) -> str:
    """Generate self-checking Verilog-2001 testbench for registered wrapper module.

    Per spec docs/02 §6, §7:
    - Fixed latency L (default 1).
    - Drives clk, rst_n, valid_in, x_flat.
    - Monitors valid_out and checks y_flat against y_exp.hex.
    - Prints exactly one summary line:
      TB_RESULT CHECKED=<n> MISMATCH=<m> TIMING_ERR=<t>
    """
    if module_name is None:
        raw_name = f"llmhw_{op.name}"
        dut_module = sanitize_identifier(raw_name)
    else:
        dut_module = sanitize_identifier(module_name)

    tb_module = f"{dut_module}_tb"
    k = op.in_features
    n = op.out_features
    in_bits = 8 * k
    out_bits = 32 * n

    total_x_elements = num_vectors * k
    total_y_elements = num_vectors * n

    lines = [
        "// =============================================================================",
        f"// Wrapper Testbench for: {dut_module}",
        f"// Vectors: {num_vectors}, K={k}, N={n}, Latency={latency}",
        "// Generated by LLMHW compiler — strictly deterministic, no timestamps",
        "// =============================================================================",
        "`timescale 1ns / 1ps",
        "`default_nettype none",
        "",
        f"module {tb_module};",
        "",
        f"    parameter NUM_VECTORS = {num_vectors};",
        f"    parameter K = {k};",
        f"    parameter N = {n};",
        "",
        "    reg                    clk;",
        "    reg                    rst_n;",
        "    reg                    valid_in;",
        f"    reg  [{in_bits - 1}:0]  x_flat;",
        "    wire                   valid_out;",
        f"    wire [{out_bits - 1}:0] y_flat;",
        "",
        f"    reg [7:0]  x_mem [0:{total_x_elements - 1}];",
        f"    reg [31:0] y_mem [0:{total_y_elements - 1}];",
        "",
        "    integer vec_in_idx, vec_out_idx, k_idx, n_idx;",
        "    integer checked_count = 0;",
        "    integer mismatch_count = 0;",
        "    integer timing_err_count = 0;",
        "",
        "    reg signed [31:0] y_act_elem;",
        "    reg signed [31:0] y_exp_elem;",
        "",
        f"    {dut_module} dut (",
        "        .clk(clk),",
        "        .rst_n(rst_n),",
        "        .valid_in(valid_in),",
        "        .x_flat(x_flat),",
        "        .valid_out(valid_out),",
        "        .y_flat(y_flat)",
        "    );",
        "",
        "    // Clock generator: 10ns period (100 MHz)",
        "    always #5 clk = ~clk;",
        "",
        "    // Driving process",
        "    initial begin",
        "        clk = 0;",
        "        rst_n = 0;",
        "        valid_in = 0;",
        "        x_flat = 0;",
        "",
        '        if ($test$plusargs("dump")) begin',
        f'            $dumpfile("{dut_module}.vcd");',
        f"            $dumpvars(0, {tb_module});",
        "        end",
        "",
        f'        $readmemh("{x_hex_path}", x_mem);',
        f'        $readmemh("{y_hex_path}", y_mem);',
        "",
        "        // Active-low reset pulse for 2 cycles",
        "        #20;",
        "        @(posedge clk);",
        "        #1;",
        "        rst_n = 1;",
        "",
        "        // Stream vectors",
        "        for (vec_in_idx = 0; vec_in_idx < NUM_VECTORS; vec_in_idx = vec_in_idx + 1) begin",
        "            @(posedge clk);",
        "            #1;",
        "            valid_in = 1;",
        "            for (k_idx = 0; k_idx < K; k_idx = k_idx + 1) begin",
        "                x_flat[8*k_idx +: 8] = x_mem[vec_in_idx*K + k_idx];",
        "            end",
        "        end",
        "",
        "        @(posedge clk);",
        "        #1;",
        "        valid_in = 0;",
        "        x_flat = 0;",
        "    end",
        "",
        "    // Checking process",
        "    initial begin",
        "        @(posedge rst_n);",
        "        // Wait for first input transaction at posedge clk",
        "        @(posedge clk);",
        "",
        "        for (vec_out_idx = 0; vec_out_idx < NUM_VECTORS; vec_out_idx = vec_out_idx + 1) begin",
        "            @(posedge clk);",
        "            #1;",
        "            if (valid_out !== 1'b1) begin",
        '                $display("TIMING_ERR [vec=%0d]: valid_out was not 1", vec_out_idx);',
        "                timing_err_count = timing_err_count + 1;",
        "            end",
        "",
        "            for (n_idx = 0; n_idx < N; n_idx = n_idx + 1) begin",
        "                y_act_elem = y_flat[32*n_idx +: 32];",
        "                y_exp_elem = y_mem[vec_out_idx*N + n_idx];",
        "                if (y_act_elem !== y_exp_elem) begin",
        '                    $display("MISMATCH [vec=%0d, lane=%0d]: expected 0x%08h (%0d), got 0x%08h (%0d)",',
        "                             vec_out_idx, n_idx, y_exp_elem, y_exp_elem, y_act_elem, y_act_elem);",
        "                    mismatch_count = mismatch_count + 1;",
        "                end",
        "            end",
        "            checked_count = checked_count + 1;",
        "        end",
        "",
        "        #10;",
        '        $display("TB_RESULT CHECKED=%0d MISMATCH=%0d TIMING_ERR=%0d", checked_count, mismatch_count, timing_err_count);',
        "        $finish;",
        "    end",
        "",
        "endmodule",
        "`default_nettype wire",
        "",
    ]
    return "\n".join(lines)

