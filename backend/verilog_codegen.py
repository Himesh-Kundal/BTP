"""Parametric Verilog-2001 tile core code generator for Design F (T4.4).

Generates combinational tile cores for arbitrary (Nt, Kt) shapes:
- Inputs: x_flat [8*Kt-1:0]
- Outputs: y_flat [acc_bits*Nt-1:0]
- Zero weight input ports (Invariant I3)
- Explicit signed wires and signed decimal literals (8'sd, -8'sd)
- Multiplier-free +-1 pass-through and negation wires
- Omission of zero-weight product terms
- Explicit sign extension to accumulator width (default 32 bits)
"""

from __future__ import annotations

import hashlib
import re

import numpy as np

from backend.weight_encoder import encode_row_accumulation


def sanitize_identifier(name: str) -> str:
    """Sanitize string to valid Verilog identifier [a-zA-Z0-9_]."""
    cleaned = re.sub(r"[^a-zA-Z0-9_]", "_", name).lower()
    if cleaned and cleaned[0].isdigit():
        cleaned = "_" + cleaned
    return cleaned


def generate_tile_core(
    module_name: str,
    weights: np.ndarray,
    acc_bits: int = 32,
    manifest_hash: str = "",
) -> str:
    """Generate synthesizable, combinational Verilog-2001 tile core module.

    Interface:
        module <module_name> (
            input  wire [8*Kt-1:0]         x_flat,
            output wire [acc_bits*Nt-1:0]  y_flat
        );

    Args:
        module_name: Verilog module name identifier.
        weights: 2D numpy array of shape (Nt, Kt) with INT8 weights.
        acc_bits: Accumulator bit width (default 32).
        manifest_hash: Cryptographic manifest hash for header comment.

    Returns:
        Complete Verilog-2001 module source code.
    """
    weights = np.asarray(weights, dtype=np.int8)
    if weights.ndim != 2:
        raise ValueError(f"Weights must be 2D array, got shape {weights.shape}")

    nt, kt = weights.shape
    mod_name = sanitize_identifier(module_name)
    in_bits = 8 * kt
    out_bits = acc_bits * nt

    if not manifest_hash:
        manifest_hash = hashlib.sha256(weights.tobytes()).hexdigest()[:16]

    lines = [
        "// =============================================================================",
        f"// Fixed-weight tile core: {mod_name}",
        f"// Shapes: Nt={nt}, Kt={kt}, acc_bits={acc_bits}",
        f"// Manifest SHA256: {manifest_hash}",
        "// Generated by LLMHW compiler — strictly deterministic, no timestamps",
        "// =============================================================================",
        "`default_nettype none",
        "/* verilator lint_save */",
        "/* verilator lint_off WIDTHEXPAND */",
        "/* verilator lint_off UNUSEDSIGNAL */",
        "/* verilator lint_off DECLFILENAME */",
        "",
        f"module {mod_name} (",
        f"    input  wire [{in_bits - 1}:0] x_flat,",
        f"    output wire [{out_bits - 1}:0] y_flat",
        ");",
        "",
        "    // --- Input Unpacking (explicit signed wires) ---",
    ]

    for j in range(kt):
        lines.append(f"    wire signed [7:0] x_{j} = x_flat[{8 * j + 7}:{8 * j}];")

    lines.append("")
    lines.append("    // --- Multipliers & Accumulations ---")

    for i in range(nt):
        lines.append(f"    // Row {i}:")
        decls, sum_expr = encode_row_accumulation(
            row_idx=i,
            weights_row=weights[i],
            x_prefix="x",
            p_prefix=f"p_{i}",
            acc_bits=acc_bits,
        )
        for decl in decls:
            lines.append(f"    {decl}")
        lines.append(f"    wire signed [{acc_bits - 1}:0] y_{i} = {sum_expr};")
        lines.append(f"    assign y_flat[{acc_bits * i + acc_bits - 1}:{acc_bits * i}] = y_{i};")
        lines.append("")

    lines.append("endmodule")
    lines.append("/* verilator lint_restore */")
    lines.append("`default_nettype wire")
    lines.append("")

    return "\n".join(lines)
